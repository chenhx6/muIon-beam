import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(process.argv[2] || path.resolve(import.meta.dirname, '../../../..'));
const policy = path.join(root, '00_project/config/naming_policy.yaml');
const output = path.join(root, '00_project/traceability/FILE_NAMING_GLOSSARY.md');
const text = fs.readFileSync(policy, 'utf8');
const rows = [];
let inAbbreviations = false;
for (const line of text.split(/\r?\n/)) {
  if (line === 'abbreviations:') { inAbbreviations = true; continue; }
  if (inAbbreviations && line && !line.startsWith('  ')) break;
  const match = line.match(/^  ([a-z][a-z0-9_]*)\s*:\s*\{\s*expansion:\s*([^,]+),\s*zh:\s*([^,]+),\s*category:\s*([^}]+)\}/);
  if (match) rows.push(match.slice(1).map((v) => v.trim()));
}
const table = rows.map(([token, expansion, zh]) => `| \`${token}\` | ${expansion} | ${zh} |`).join('\n');
const body = '# File Naming Glossary\n\nGenerated from `00_project/config/naming_policy.yaml`. Do not edit this file directly.\n\n## Format\n\n```text\nYYYYMMDD_HHMM-object_id-topic-artifact_type-vNN-locale.extension\n```\n\nThe timestamp is one field. Its internal separator is `_`; later fields use `-`; words inside fields use lower `snake_case`.\n\n## Stable identifiers\n\nThe numeric suffix is a registration sequence within its object namespace. It is not a physical parameter.\n\n## Controlled abbreviations\n\n| Token | Expansion | Meaning |\n|---|---|---|\n' + table + '\n\n## Update rule\n\nAdd new terms to the YAML policy. The build script regenerates this glossary and the catalog checks for unregistered terms.\n';
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, body, 'utf8');
console.log(JSON.stringify({ output: path.relative(root, output).replaceAll('\\\\', '/'), abbreviations: rows.length }, null, 2));
